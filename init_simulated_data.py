def generate_messages():
    messages = []
    msg_id = 1

    SCATTER = 0.005

    for event in EVENTS_DATA:
        base_lat = event.get('base_lat', 39.92)
        base_lng = event.get('base_lng', 116.40)

        for desc in event['descriptions']:
            platform = random.choice(PLATFORMS)
            time_offset = random.randint(0, 7200)
            publish_time = datetime.now() - timedelta(seconds=time_offset)

            lat = base_lat + random.uniform(-SCATTER, SCATTER)
            lng = base_lng + random.uniform(-SCATTER, SCATTER)

            message = {
                'id': msg_id,
                'original_text': desc,
                'cleaned_text': None,
                'publisher_name': random.choice(PUBLISHER_NAMES),
                'publish_time': publish_time,
                'create_time': publish_time,
                'location_text': event['location'],
                'lat': round(lat, 6),
                'lng': round(lng, 6),
                'source_platform': platform,
                'status': 0,
                'ai_analysis': None,
                'incident_id': None
            }
            messages.append(message)
            msg_id += 1

    random.shuffle(messages)
    return messages

def init_simulated_data():
    conn = pymysql.connect(**db_config)
    cursor = conn.cursor()

    try:
        print("清空现有数据...")
        cursor.execute('DELETE FROM dispatch_tasks')
        cursor.execute('DELETE FROM incident_evidences')
        cursor.execute('DELETE FROM review_logs')
        cursor.execute('DELETE FROM incidents')
        cursor.execute('DELETE FROM messages')
        cursor.execute('UPDATE responders SET status = 1, current_incident_id = NULL')

        print(f"生成 {len(EVENTS_DATA)} 个事件的 {len(EVENTS_DATA) * 10} 条模拟消息...")
        messages = generate_messages()

        for msg in messages:
            cursor.execute('''
                INSERT INTO messages (id, original_text, cleaned_text, publisher_name, publish_time,
                create_time, location_text, lat, lng, source_platform, status, ai_analysis, incident_id)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
            ''', (
                msg['id'], msg['original_text'], msg['cleaned_text'], msg['publisher_name'],
                msg['publish_time'], msg['create_time'], msg['location_text'],
                msg['lat'], msg['lng'], msg['source_platform'], msg['status'],
                msg['ai_analysis'], msg['incident_id']
            ))

        conn.commit()
        total_rumors = sum(1 for e in EVENTS_DATA if e.get('is_rumor'))
        total_real = sum(1 for e in EVENTS_DATA if not e.get('is_rumor'))
        print(f"成功初始化 {len(messages)} 条消息（{len(EVENTS_DATA)} 个事件）")
        print(f"  真实事件: {total_real} 个")
        print(f"  谣言事件: {total_rumors} 个（占比 {total_rumors/len(EVENTS_DATA)*100:.0f}%）")
        types = {}
        for e in EVENTS_DATA:
            types[e['type']] = types.get(e['type'], 0) + 1
        print(f"  灾种分布: {', '.join(f'{k}:{v}' for k, v in types.items())}")

    except Exception as e:
        conn.rollback()
        print(f"初始化失败: {e}")
        import traceback
        traceback.print_exc()
    finally:
        cursor.close()
        conn.close()

